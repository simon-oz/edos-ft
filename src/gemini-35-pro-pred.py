import pandas as pd
import re
from pathlib import Path

# Load the dataset
df = pd.read_csv("data/processed/llm_fewshot/test_id_text.csv")

# Define the naive keyword patterns used for the baseline classification
sexist_keywords = [
    r'\bbitch', r'\bcunt', r'\bwhore', r'\bslut', r'\bfeminazi', r'\bthot', 
    r'\bhypergamy\b', r'women make bad', r'women want to be', r'act like a woman',
    r'female brain', r'dumb broad', r'stupid woman', r'ugly bitch', r'\bskank', r'\bhoes\b'
]
pattern = re.compile('|'.join(sexist_keywords), re.IGNORECASE)

# Classification function
def classify(text):
    if pd.isna(text):
        return 'none'
    if pattern.search(str(text)):
        return 'sexist'
    return 'none'

# Apply the classification
df['predicted'] = df['text'].apply(classify)

# Save to a new CSV file, keeping the same order and returning only the requested format
out_path = Path("data/processed/llm_fewshot/gemini3-1-pro/predicted-by-code.csv")
out_path.parent.mkdir(parents=True, exist_ok=True)   # create dir if missing
df.to_csv(out_path, index=False)
print(f"Classification complete. File saved as '{out_path}'.")